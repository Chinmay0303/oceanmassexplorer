"""Generate src/colormap-stops.js: colour stops sampled from cmocean (thermal, haline, oxy) and matplotlib (viridis, cividis).

Usage: pip install cmocean matplotlib && python tools/gen_colormaps.py
Only needed when the map list changes; the generated file is committed so the app has no dependencies.
cmocean: Thyng et al. (2016), Oceanography 29(3), MIT licence.
"""
import cmocean
import matplotlib
import numpy as np

N = 32  # stops per map; the app interpolates linearly between them
MAPS = [
    ("thermal", "Oceanographic: thermal / haline / oxy", cmocean.cm.thermal),
    ("haline", "", cmocean.cm.haline),
    ("oxy", "", cmocean.cm.oxy),
    ("viridis", "Viridis", matplotlib.colormaps["viridis"]),
    ("cividis", "Cividis (colour-blind safe)", matplotlib.colormaps["cividis"]),
]

lines = [
    "// GENERATED by tools/gen_colormaps.py - do not edit. Colour stops (32 per map, linear interpolation).",
    "// thermal, haline, oxy: cmocean (Thyng et al. 2016, MIT licence); viridis, cividis: matplotlib.",
    "export const STOPS = {",
]
for key, _, cm in MAPS:
    hexes = ["#%02x%02x%02x" % tuple(int(round(255 * v)) for v in cm(float(x))[:3]) for x in np.linspace(0, 1, N)]
    lines.append(f"  {key}: {hexes!r},".replace("'", '"'))
lines.append("};")
open("src/colormap-stops.js", "w").write("\n".join(lines) + "\n")
print("wrote src/colormap-stops.js")
